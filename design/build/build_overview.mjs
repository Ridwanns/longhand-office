// Build design/preview/series.js for Sheet 01 Overview from the Office snapshot (.pages-data):
//   SERIES   completed daily closes since 24 Apr 2025 for IHSG, S&P 500, TLT, gold futures (market-history.json)
//   YIELD    latest US Treasury par yields, 2/5/10/20/30 years (official-rates.json)
//   OVERVIEW dates, Indonesia GDP/CPI/BI rate and the latest-release quad (macro.json, macro-context.json)
// usage: node build_overview.mjs <repo> [dataDir]
import fs from 'fs'; import path from 'path';
const repo = path.resolve(process.argv[2] || '.'), data = path.resolve(repo, process.argv[3] || '.pages-data');
const J = f => JSON.parse(fs.readFileSync(path.join(data, f), 'utf8'));
const MH = J('market-history.json'), RATES = J('official-rates.json'), MACRO = J('macro.json'), CTX = J('macro-context.json');
const START = '2025-04-24';
function completed(pts, q) { // same rule as build_markets_sheet: no intraday point on the retrieval day before 17:00 exchange time
  if (!pts.length || !q.retrievedAt) return pts;
  const tz = q.exchangeTimezoneName || 'America/New_York', at = new Date(q.retrievedAt);
  const day = new Intl.DateTimeFormat('en-CA', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit' }).format(at);
  const hour = +new Intl.DateTimeFormat('en-GB', { timeZone: tz, hour: '2-digit', hourCycle: 'h23' }).format(at);
  return pts.at(-1)[0] === day && hour < 17 ? pts.slice(0, -1) : pts;
}
const SERIES = {}, META = {};
for (const sym of ['^JKSE', '^GSPC', 'TLT', 'GC=F']) {
  const e = MH.entries.find(x => x.symbol === sym); if (!e?.quote) throw Error('Missing ' + sym + ' in market-history.json');
  const q = e.quote, pts = completed(q.history.filter(h => Number.isFinite(h.close)).map(h => [h.date, Math.round(h.close * 100) / 100]), q).filter(p => p[0] >= START);
  SERIES[sym] = pts; META[sym] = { last: pts.at(-1)[0], retrieved: q.retrievedAt, source: q.sourceUrl, name: q.name };
}
const obs = RATES.observations.filter(o => o.rates), last = obs.at(-1);
const TEN = [['2 Yr', 2], ['5 Yr', 5], ['10 Yr', 10], ['20 Yr', 20], ['30 Yr', 30]];
const YIELD = { date: last.date, retrievedAt: RATES.retrievedAt, sourceUrl: RATES.sourceUrl, points: TEN.filter(([m]) => Number.isFinite(last.rates[m])).map(([m, y]) => ({ tenor: m, years: y, value: last.rates[m] })), spreadBp: Math.round((last.rates['10 Yr'] - last.rates['2 Yr']) * 100) };
const series = id => [...MACRO.series, ...CTX.series].find(s => s.id === id);
const pts = id => (series(id)?.observations || []).filter(o => Number.isFinite(o.value));
const gdp = pts('id-gdp'), cpi = pts('id-cpi'), bi = pts('id-policy');
const quad = (g, i) => g === 0 || i === 0 ? null : g > 0 ? (i < 0 ? 1 : 2) : (i > 0 ? 3 : 4);
const q = quad(gdp.at(-1).value - gdp.at(-2).value, cpi.at(-1).value - cpi.at(-2).value);
const OVERVIEW = { builtAt: new Date().toISOString(), marketSnapshot: MH.publishedAt || MH.generatedAt || META['^JKSE'].retrieved, meta: META,
  idn: { gdp: gdp.slice(-3).map(o => ({ period: o.period, value: o.value, url: o.sourceUrl || '' })), cpi: cpi.slice(-2).map(o => ({ period: o.period, value: o.value, url: o.sourceUrl || '' })),
    bi: { date: bi.at(-1).date, value: bi.at(-1).value }, quad: q, gdpReleased: gdp.at(-1).releasedAt || null } };
const file = path.join(repo, 'design', 'preview', 'series.js');
fs.writeFileSync(file, `// Generated by design/build/build_overview.mjs from ${path.basename(data)} — do not edit by hand.\nwindow.SERIES=${JSON.stringify(SERIES)};\nwindow.YIELD=${JSON.stringify(YIELD)};\nwindow.OVERVIEW=${JSON.stringify(OVERVIEW)};\n`);
console.log('series', Object.entries(SERIES).map(([k, v]) => `${k} ${v.length} → ${v.at(-1)[0]} ${v.at(-1)[1]}`).join(' | '));
console.log('yield', YIELD.date, YIELD.points.map(p => p.tenor + ' ' + p.value).join(', '), 'spread', YIELD.spreadBp, 'bp');
console.log('idn', JSON.stringify(OVERVIEW.idn));
