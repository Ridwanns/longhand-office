"""Port design preview sheet 02 (Macro) into live modules.
Writes: sheet-macro.css, sheet-macro-map.js, sheet-macro-sections.js, sheet-macro-calendar.js (repo root).
usage: python port_macro.py <repo>"""
import io, re, sys, os
repo = sys.argv[1]; P = lambda *a: os.path.join(repo, *a)
rd = lambda p: io.open(p, encoding='utf-8').read()
def wr(p, s):
    # inline styles become data-css: the sheet host applies them through the CSSOM (the CSP blocks style attributes)
    if p.endswith('.js'): s = s.replace(' style="', ' data-css="')
    io.open(p, 'w', encoding='utf-8', newline='\n').write(s)
def rep(s, a, b, count=1):
    assert s.count(a) == count, (a[:100], s.count(a)); return s.replace(a, b)

# ---------------- CSS: scope every rule to this sheet (.lh-sheet-macro) ----------------
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sheetport as SP
html = rd(P('design', 'preview', 'macro.html'))
inline = html[html.index('<style>') + 7:html.index('</style>')]
css_src = inline + '\n' + rd(P('design', 'preview', 'office-ui.css')) + '\n' + rd(P('design', 'preview', 'macro-sections.css')) + '\n' + rd(P('design', 'preview', 'identity.css'))
scoped = SP.scope_block(css_src, '.lh-sheet-macro')
head = ('/* Sheet 02 Macro, ported from design/preview (macro.html, macro-sections.css, office-ui.css, identity.css).\n'
        '   Every rule is scoped to .lh-sheet-macro so it cannot reach the rest of the Office. Generated by the port script;\n'
        '   the bindings at the end tie the sheet to the live identity: Newsreader headings, Plex text and figures. */\n')
extra = '.lh-sheet-macro #indseg{max-width:100%;overflow-x:auto;scrollbar-width:none}.lh-sheet-macro #indseg button{flex:none}\n'
wr(P('sheet-macro.css'), head + scoped + SP.bindings('.lh-sheet-macro') + extra)

