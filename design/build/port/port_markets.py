"""Port design preview sheet 03 (Markets) and the shared view switcher into live modules.
Writes: sheet-markets.css, sheet-markets-desks.js, sheet-markets-lead.js, sheet-views.js, sheet-markets-page.js."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sheetport as SP
repo = sys.argv[1]; P = lambda *a: os.path.join(repo, *a); D = lambda f: SP.rd(P('design', 'preview', f)); rep = SP.rep
html = D('markets.html')
inline = html[html.index('<style>') + 7:html.index('</style>')]
css = SP.scope_block('\n'.join([inline, D('office-ui.css'), D('macro-sections.css'), D('markets.css'), D('identity.css')]), '.lh-sheet-markets')
SP.wr(P('sheet-markets.css'), '/* Sheet 03 Markets, ported from design/preview (markets.html, office-ui.css, macro-sections.css, markets.css,\n'
      '   identity.css). Scoped to .lh-sheet-markets. Generated by the port script. */\n' + css + SP.bindings('.lh-sheet-markets'))

# desks
s = D('markets.js')
s = rep(s, "(function(){\nconst K=window.MARKETS;if(!K)return;", "export function mountMarketsDesks(dataBase){\nconst K=window.MARKETS;if(!K)return;")
s = s.rstrip(); assert s.endswith('})();'); s = s[:-5] + '}\n'
s = rep(s, "async function load(file){if(!cache[file])cache[file]=fetch(file).then(r=>r.json());return cache[file]}",
        "async function load(file){if(!cache[file])cache[file]=fetch(new URL(file,dataBase),{credentials:'omit',cache:'no-store'}).then(r=>{if(!r.ok)throw Error('Instrument history unavailable');return r.json()});return cache[file]}")
s = rep(s, "const S=JSON.parse(localStorage.getItem('lh-watch-'+id)||'null');", "let S=null;try{S=JSON.parse(localStorage.getItem('lh-watch-'+id)||'null')}catch(e){}")
a = s.index("  const h=decodeURIComponent(location.hash.slice(1));if(h.startsWith('i=')){"); b = s.index('\n', a)
s = s[:a] + "  // the instrument is chosen in its desk; the URL hash stays the Office route" + s[b:]
s = rep(s, "document.readyState==='loading'?document.addEventListener('DOMContentLoaded',all):all();", "all();")
assert 'location.hash' not in s
# live wording and live routes instead of preview placeholders
for a, b in [
 ('<a href="#" class="act">Research this instrument →</a>', '<a href="#quant/section/ticker" class="act">Research this instrument →</a>'),
 ('<a href="#" class="act">Run models →</a>', '<a href="#quant" class="act">Run models →</a>'),
 ('<a href="#" class="act">Use for valuation →</a>', '<a href="#quant/section/valuation" class="act">Use for valuation →</a>'),
 ('Open in Research Lab (Sheet 04, not yet designed)', 'Opens in Research Lab'),
 ("addNote:'In the live app any listed ticker can be added.'", "addNote:'Instruments in the published market list can be added here. The full watchlist and any listed ticker are in US stocks & ETFs.'"),
 ('Optional TradingView chart: loads a third-party widget on request in the live app; not embedded in this preview.', 'Optional TradingView chart: in US stocks &amp; ETFs, where it loads a third-party widget only on request.'),
 ('has no published history in this preview. Available:', 'has no published history on this sheet. Available:'),
 ("'Daily view beyond 3 years uses weekly points in this preview.'", "'Daily view beyond 3 years uses weekly points.'")]:
    s = rep(s, a, b)
SP.wr(P('sheet-markets-desks.js'), "// Sheet 03 Markets: every desk, rendered from the published sheet data. Ported from design/preview/markets.js.\n"
      "// The watchlist chosen here only selects which instruments this sheet shows; it is kept in this browser.\n" + s)

# lead: a general headline; the data sentence opens the paragraph
l = D('markets-lead.js')
l = rep(l, "(function(){\nconst K=window.MARKETS;if(!K)return;", "export function mountMarketsLead(){\nconst K=window.MARKETS;if(!K)return;")
l = l.rstrip(); assert l.endswith('})();'); l = l[:-5] + '}\n'
a = l.index("document.getElementById('mk-head').textContent="); b = l.index('\n', a)
lead = l[a:b]; sentence = lead[lead.index('=') + 1:].rstrip(';')
l = l[:a] + "const opening=" + sentence + ";" + l[b:]
l = rep(l, "document.getElementById('mk-dek').innerHTML=`", "document.getElementById('mk-dek').innerHTML=opening+' '+`")
SP.wr(P('sheet-markets-lead.js'), "// Sheet 03 Markets: the opening paragraph, written from the data (plain facts). Ported from design/preview/markets-lead.js.\n" + l)

# shared view switcher
v = D('sheet-views.js')
v = rep(v, "(function(){\nconst $=s=>document.querySelector(s)", "export function mountSheetViews(listen,page){\nconst $=s=>document.querySelector(s)")
v = v.rstrip(); assert v.endswith('})();'); v = v[:-5] + '}\n'
v = re.sub(r"const page=\(location\.pathname[^\n]*\n", "", v, count=1)
v = v.replace("$('main .lead-sec')", "$('.lh-sheet-body .lead-sec')").replace("$$('main > section')", "$$('.lh-sheet-body > section')").replace("$$('main > section[id]')", "$$('.lh-sheet-body > section[id]')").replace("main=$('main')", "main=$('.lh-sheet-body')")
assert "$('main" not in v and "$$('main" not in v, [x for x in v.split('\n') if "'main" in x]
v = re.sub(r"\n    if\(push&&prev!==null&&prev!==v\)\{try\{history\.pushState[^\n]*", "", v)
v = rep(v, "  document.addEventListener('click',e=>{const b=e.target.closest('[data-view]')", "  listen(document,'click',e=>{const b=e.target.closest('[data-view]')")
v = re.sub(r"\n  addEventListener\('popstate'[^\n]*", "", v); v = re.sub(r"\n  addEventListener\('hashchange'[^\n]*", "", v)
v = rep(v, "  const h=location.hash.slice(1);show(allIds.includes(h)?h:'overview',{push:false,scroll:false});", "  show('overview',{push:false,scroll:false});")
v = rep(v, "document.readyState==='loading'?document.addEventListener('DOMContentLoaded',whenReady):whenReady();", "whenReady();")
assert 'location.' not in v and 'pushState' not in v, [x for x in v.split('\n') if 'location.' in x or 'pushState' in x]
SP.wr(P('sheet-views.js'), "// Shared sheet views (overview + deep-analysis chooser + one view per section). Ported from design/preview/sheet-views.js;\n"
      "// views switch inside the page and the URL hash stays the Office route.\n" + v)

# page
body = html[html.index('<nav class="mtabs"'):html.index('<footer>')]
body = body.replace('<main>', '<div class="lh-sheet-body">').replace('</main>', '</div>')
body = body.replace('<h1 id="mk-head">Markets</h1>', '<h1 id="mk-head">Markets</h1>')
assert '`' not in body and '${' not in body
foot = ('<div class="lh-sheet-foot"><span>Prices: Yahoo Finance daily closes from the published Office snapshot, completed sessions. Treasury curve: U.S. Department of the Treasury.</span>'
        '<span>Not investment advice. No orders are placed from the Office.</span></div>')
js = ("// Sheet 03 Markets: page markup and mount. Markup from design/preview/markets.html; the header is the Office's own.\n"
      "import {loadSheetData,hostSheet} from './sheet-host.js';\nimport {mountMarketsDesks} from './sheet-markets-desks.js';\nimport {mountMarketsLead} from './sheet-markets-lead.js';\nimport {mountSheetViews} from './sheet-views.js';\n"
      "let host=null;\n"
      "export function marketsSheetPage(){return `<div class=\"lh-sheet lh-sheet-markets\" data-sheet=\"markets\">" + re.sub(r'\n\s*', '', body) + foot + "</div>`;}\n"
      "export async function mountMarketsSheet(){\n"
      " const root=document.querySelector('[data-sheet=\"markets\"]');if(!root)return;host?.stop();host=hostSheet(root);const own=host;\n"
      " try{await loadSheetData(['markets-sheet']);}\n"
      " catch{if(root.isConnected)root.querySelector('#mk-dek').textContent='The published markets sheet could not be read. No values are shown in its place.';return;}\n"
      " if(!root.isConnected||own!==host)return;\n"
      " mountMarketsDesks(new URL('./sheet-data/',import.meta.url));mountMarketsLead();mountSheetViews(host.listen,'markets');\n"
      "}\n")
SP.wr(P('sheet-markets-page.js'), js)
print('markets css', len(css), 'desks', len(s), 'views', len(v))
