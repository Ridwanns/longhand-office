"""Port the styles of design preview sheet 05 (Portfolio). Writes sheet-portfolio.css (repo root).
The sheet's markup and mount are hand-written in sheet-portfolio-page.js: the preview's example ledgers are not used,
and every section holds the Office's own portfolio components, so each figure comes from the tested ledger."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sheetport as SP
repo = sys.argv[1]; P = lambda *a: os.path.join(repo, *a); D = lambda f: SP.rd(P('design', 'preview', f))
html = D('portfolio.html')
inline = html[html.index('<style>') + 7:html.index('</style>')]
css = SP.scope_block('\n'.join([inline, D('office-ui.css'), D('macro-sections.css'), D('markets.css'), D('research.css'), D('identity.css')]), '.lh-sheet-portfolio')
extra = ('/* the Office components placed in each section */\n'
         '.lh-sheet-portfolio .lh-embedded{display:grid;gap:16px;margin-top:14px;min-width:0}\n'
         '.lh-sheet-portfolio .lh-embedded>:is(section,details,nav,div,dl){margin:0;min-width:0}\n'
         '.lh-sheet-portfolio .lh-embedded .lh-intro-hidden>:is(.section-heading,.eyebrow:first-child,h2:first-of-type){display:none}\n'
         '.lh-sheet-portfolio .lh-embedded .table-wrap{overflow-x:auto}\n'
         '.lh-sheet-portfolio .lh-sheet-empty{padding:14px 0;color:var(--ink2)}\n'
         '.lh-sheet-portfolio .lh-sheet-empty a{color:var(--focus);font-weight:500}\n'
         '.lh-sheet-portfolio .lh-portfolio-list{display:grid;gap:8px;margin:10px 0 0;padding:0;list-style:none}\n'
         '.lh-sheet-portfolio .lh-portfolio-list a{display:flex;justify-content:space-between;gap:12px;padding:10px 12px;border:1px solid var(--rule);border-radius:4px;color:var(--ink)}\n'
         '.lh-sheet-portfolio .lh-portfolio-list a:hover{border-color:var(--focus)}\n'
         '.lh-sheet-portfolio .pg.on{box-shadow:inset 0 0 0 1px var(--focus)}\n'
         '.lh-sheet-portfolio .pg .btn-line,.lh-sheet-portfolio .pg button{align-self:flex-start;margin-top:10px}\n')
SP.wr(P('sheet-portfolio.css'), '/* Sheet 05 Portfolio, styles ported from design/preview (portfolio.html and the shared preview CSS).\n'
      '   Scoped to .lh-sheet-portfolio. Generated by design/build/port/port_portfolio.py. */\n' + css + SP.bindings('.lh-sheet-portfolio') + extra)
print('portfolio css', len(css))
