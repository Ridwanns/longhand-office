// Build design/preview/records-sheet.js for Sheet 06 Records & Data Sources from .pages-data/data-coverage.json.
// Attention flags follow the app's descriptive rules: unavailable, older acquisition (10 days), older observation
// (threshold by cadence), stock/ETF model inputs not ready, and gaps where a later supplied period has no value.
import fs from 'fs'; import path from 'path';
const repo = process.argv[2];
const C = JSON.parse(fs.readFileSync(path.join(repo, '.pages-data', 'data-coverage.json'), 'utf8'));
// Same rule as the app's coverageFreshness() in data-coverage.js, evaluated on the build date.
const NOW = Date.parse(process.argv[3] || '2026-11-13T12:00:00Z'), DAY = 864e5;
const OBS_DAYS = { D: 10, W: 21, M: 75, Q: 210, A: 550, E: 120 };
const iso = s => typeof s === 'string' && !Number.isNaN(Date.parse(s));
function freshness(r) {
  let end = r.observedAt;
  if (end && ['Q', 'M'].includes(r.frequency)) { const d = new Date(end + 'T00:00:00Z'); end = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + ({ Q: 3, M: 1 }[r.frequency]), 0)).toISOString().slice(0, 10) }
  if (end && r.frequency === 'A' && end.endsWith('-01-01')) end = end.slice(0, 4) + '-12-31';
  return { acq: iso(r.retrievedAt) && NOW - Date.parse(r.retrievedAt) > 10 * DAY, obs: iso(end) && NOW - Date.parse(end) > (OBS_DAYS[r.frequency] || 30) * DAY };
}
const flags = r => {
  const f = [], fr = freshness(r);
  if (!r.available) f.push('Unavailable');
  if (fr.acq) f.push('Older acquisition');
  if (fr.obs) f.push('Older observation');
  if (r.coverage && r.coverage.history && !r.coverage.modelReady) f.push('Stock/ETF model inputs not ready');
  if (r.reason && !/^No numeric|^SEC request|^Yahoo screener/.test(r.reason)) f.push('Gap with another connected series');
  if (r.reason && !f.length) f.push('Source note');
  return f.filter((x, i, a) => a.indexOf(x) === i);
};
// "Needs attention" in the app: !available || acquisitionOld || observationOld || reason
const attentionRule = r => { const fr = freshness(r); return !r.available || fr.acq || fr.obs || !!r.reason };
const areas = {};
const attention = [];
for (const r of C.records) {
  const a = areas[r.group] || (areas[r.group] = { total: 0, available: 0, unavailable: 0, attention: 0 });
  a.total++; r.available ? a.available++ : a.unavailable++;
  const f = flags(r);
  if (attentionRule(r)) { a.attention++; attention.push({ id: r.id, g: r.group, l: r.label, s: r.scope, m: r.metric, f: r.frequency, u: r.unit, n: r.count, av: r.available, ob: r.observedAt, rt: r.retrievedAt, src: r.source, url: r.sourceUrl, why: r.reason, alt: (r.alternatives || []).length, cov: r.coverage || null, fl: f, v: r.latestValue }) }
}
// a small, honest sample of healthy records per area for the "All connected series" view
const healthy = {}; for (const r of C.records) { if (attentionRule(r)) continue; const h = healthy[r.group] || (healthy[r.group] = []); if (h.length < 40) h.push({ id: r.id, g: r.group, l: r.label, s: r.scope, m: r.metric, f: r.frequency, u: r.unit, n: r.count, av: true, ob: r.observedAt, rt: r.retrievedAt, src: r.source, url: r.sourceUrl, alt: (r.alternatives || []).length, cov: r.coverage || null, fl: [], v: r.latestValue }) }
const flagCount = {}; for (const a of attention) for (const f of a.fl) flagCount[f] = (flagCount[f] || 0) + 1;
const out = { checkedAt: new Date(NOW).toISOString(), generatedAt: C.generatedAt, summary: C.summary, publications: C.publications, policy: C.policy, areas, flagCount, attention, healthy,
  csvColumns: 'symbol,market,exchange,currency,provider,retrievedAt,timezone,interval,session,date,open,high,low,close,volume,complete,adjustment,adjustmentMethod,adjustmentEvidence,permissionEvidence,sourceUrl'.split(',') };
const file = path.join(repo, 'design', 'preview', 'records-sheet.js');
fs.writeFileSync(file, '// Generated by design/build/build_records_sheet.mjs — do not edit by hand.\nwindow.RECORDS=' + JSON.stringify(out) + ';\n');
console.log('records', C.records.length, '| attention', attention.length, '| flags', JSON.stringify(flagCount), '| bytes', fs.statSync(file).size);
console.log('areas', JSON.stringify(areas));
